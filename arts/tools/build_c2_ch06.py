def jeonggan():
    """정간보 한 줄(세로 6칸)과 칸마다의 율명을 단순화한 그림"""
    els = []
    names = ["황", "태", "중", "임", "남", "임"]
    for k, n in enumerate(names):
        y = (5 - k) * 1.2
        els += [rect(2, y, 1.6, 1.15, hl=(k == 0)), text([2.8, y + 0.58], n, hl=(k == 0))]
    els += [text([0.6, 6.6], "읽는 방향"), seg([0.6, 6.1], [0.6, 0.4], hl=True), seg([0.6, 0.4], [0.35, 0.9], hl=True), seg([0.6, 0.4], [0.85, 0.9], hl=True),
            text([5.4, 3.6], "한 칸 = 한 박"), {"t": "pt", "p": [7.0, 3.6], "hide": True}]
    return fig("정간보 한 줄. 우물 정 자 모양의 칸이 세로로 이어지고 칸마다 율명 황 태 중 임 남이 적혀 있으며, 위에서 아래로 읽는다", els, maxh=210)

def jangdan_fig(name, beats, marks):
    """장단을 박 수만큼 칸으로 그리고, 구음 표시"""
    els = [text([beats / 2, 2.4], name)]
    for k in range(beats):
        els.append(rect(k, 0, 0.95, 1.3, hl=k in marks))
        if k in marks: els.append(text([k + 0.47, 0.65], marks[k], hl=True))
        els.append(text([k + 0.47, -0.5], str(k + 1)))
    return fig(f"{name}을 칸으로 나타낸 그림", els, maxh=110)

