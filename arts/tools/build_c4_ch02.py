def arc(cx, cy, r, a0, a1, n=16, hl=False):
    pts = [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * k / n)), cy + r * math.sin(math.radians(a0 + (a1 - a0) * k / n))) for k in range(n + 1)]
    return [seg([round(a[0], 3), round(a[1], 3)], [round(b[0], 3), round(b[1], 3)], hl=hl) for a, b in zip(pts, pts[1:])]


