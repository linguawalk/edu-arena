def blocks(alt, parts, maxh=120):
    """parts: [(글자, 길이, 강조)] → 가로로 이어진 칸"""
    els, x = [], 0
    for lab, w, h in parts:
        els += [rect(x, 0, w - 0.15, 1.6, hl=h), text([x + (w - 0.15) / 2, 0.8], lab, hl=h)]
        x += w
    return fig(alt, els, maxh=maxh)

