def wheel(mark=None):
    els = []
    for k, (n, c) in enumerate(HUES):
        a0, a1 = math.radians(90 - k * 36 - 18), math.radians(90 - k * 36 + 18)
        pts = [[0, 0]] + [[round(3 * math.cos(a0 + (a1 - a0) * t / 6), 3), round(3 * math.sin(a0 + (a1 - a0) * t / 6), 3)] for t in range(7)]
        els.append(poly(pts, color=c))
        am = math.radians(90 - k * 36)
        els.append(text([round(3.75 * math.cos(am), 3), round(3.75 * math.sin(am), 3)], n, hl=(mark and n in mark)))
    if mark and len(mark) == 2:
        i, j = [next(k for k, h in enumerate(HUES) if h[0] == m) for m in mark]
        ai, aj = math.radians(90 - i * 36), math.radians(90 - j * 36)
        els.append(seg([round(2.2 * math.cos(ai), 3), round(2.2 * math.sin(ai), 3)], [round(2.2 * math.cos(aj), 3), round(2.2 * math.sin(aj), 3)], hl=True))
    return fig("먼셀의 10색상환: 빨강 주황 노랑 연두 초록 청록 파랑 남색 보라 자주가 둥글게 놓여 있다" + (f". {mark[0]}과 {mark[1]}이 선으로 이어져 있다" if mark and len(mark) == 2 else ""), els, maxh=230)

