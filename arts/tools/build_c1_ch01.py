    els = []
    for (x1, y1, _), (x2, y2, _) in zip(notes, notes[1:]):
        els.append(seg([x1 * 1.6, y1 * 0.7], [x2 * 1.6, y2 * 0.7], hl=abs(y2 - y1) >= 2))
    els += [pt([x * 1.6, y * 0.7], l, pos="n") for x, y, l in notes]
    els += [text([1.6, -1.2], "차례가기"), text([8, 3.1], "뛰어가기", hl=True)]
    return fig("도 레 미 레 솔 도 솔 미로 이어지는 가락선. 이웃한 음으로 움직이는 부분과 크게 뛰는 부분이 표시되어 있다", els, maxh=200)

