def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith(".json"): os.remove(os.path.join(OUT, f))
    idx, bad = [], 0
    for n, (sid, title, desc, essays) in enumerate(SETS, 1):
        for k, e in enumerate(essays, 1):
            e["id"] = f"code-{sid}-e{k}"
            fails = _auto(e, "\n".join(e["model"]["answer"]))
            if fails:
                bad += 1; print("예시 답안이 점검을 통과하지 못함:", e["id"], fails)
        doc = {"schema_version": "1.0", "type": "essay_set", "id": f"code-{sid}-essay", "lesson": f"code-{sid}",
               "course_title": "코딩", "chapter_title": f"{n}. {title}", "title": title, "essays": essays}
        json.dump(doc, open(os.path.join(OUT, f"{sid}.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        idx.append({"id": sid, "no": n, "title": title, "desc": desc, "count": len(essays), "key": f"code-{sid}-essay"})
    json.dump({"sets": idx}, open(os.path.join(OUT, "index.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("세트", len(SETS), "에세이", sum(len(s[3]) for s in SETS), "점검 실패", bad)
    if bad: sys.exit(1)


if __name__ == "__main__":
    main()
